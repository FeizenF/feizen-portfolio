const fs = require('fs')

const map = {
  react: 'react.svg',
  javascript: 'javascript.svg',
  python: 'python.svg',
  java: 'openjdk.svg',
  dart: 'dart.svg',
  flutter: 'flutter.svg',
  html: 'html5.svg',
  css: 'css.svg',
  git: 'git.svg',
  linux: 'linux.svg',
}

const data = JSON.parse(
  fs.readFileSync('node_modules/simple-icons/data/simple-icons.json', 'utf8')
)
const icons = data.icons || data
const out = {}

for (const [key, file] of Object.entries(map)) {
  const svg = fs.readFileSync(`node_modules/simple-icons/icons/${file}`, 'utf8')
  const title = (svg.match(/<title>(.*?)<\/title>/) || [])[1]
  const path = (svg.match(/<path d="([^"]+)"/) || [])[1]
  const entry = (Array.isArray(icons) ? icons : []).find((i) => i.title === title) || {}
  out[key] = {
    title,
    hex: `#${entry.hex || 'FFFFFF'}`,
    path,
  }
}

const source = `// Official brand marks from Simple Icons (CC0 1.0).
// Generated by scripts/build-brand-icons.cjs; paths are unmodified.
export const brandIcons = ${JSON.stringify(out, null, 2)}
`

fs.writeFileSync('src/data/brandIcons.js', source)
console.log(
  Object.keys(out)
    .map((key) => `${key}: ${out[key].title} ${out[key].hex}`)
    .join('\n')
)
