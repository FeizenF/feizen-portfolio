/**
 * Daily link check for the public work linked from this portfolio.
 *
 * The script probes each destination, then writes `src/data/siteStatus.js` so
 * the footer can show a live "system check" line. Status codes are the only
 * thing stored, which keeps the file deterministic: a second run on the same
 * day produces an identical file and therefore no extra commit.
 */
import fs from 'node:fs/promises'
import path from 'node:path'

const OUT = path.resolve('src/data/siteStatus.js')
const TIMEOUT = 12000
const USER_AGENT = 'feizen-portfolio-site-check'

const TARGETS = [
  { label: 'Student-App', url: 'https://github.com/FeizenF/Student-App' },
  {
    label: 'sistem-manajemen-mahasiswa',
    url: 'https://github.com/FeizenF/sistem-manajemen-mahasiswa',
  },
  {
    label: 'feizen-haven-hotel',
    url: 'https://github.com/FeizenF/feizen-haven-hotel',
  },
  {
    label: 'feizen-portfolio',
    url: 'https://github.com/FeizenF/feizen-portfolio',
  },
  { label: 'Profile', url: 'https://github.com/FeizenF' },
]

async function request(url, method) {
  return fetch(url, {
    method,
    redirect: 'follow',
    headers: { 'user-agent': USER_AGENT },
    signal: AbortSignal.timeout(TIMEOUT),
  })
}

async function probe(url) {
  const started = Date.now()

  try {
    let response = await request(url, 'HEAD')

    // Some hosts reject HEAD even when GET succeeds.
    if (response.status === 403 || response.status === 405) {
      response = await request(url, 'GET')
    }

    return { status: response.status, ms: Date.now() - started }
  } catch (error) {
    return { status: 0, ms: Date.now() - started, error: error.message }
  }
}

const items = await Promise.all(
  TARGETS.map(async (target) => {
    const result = await probe(target.url)
    console.log(
      `${String(result.status).padEnd(4)} ${String(result.ms).padStart(5)}ms  ${target.label}`
    )
    return { label: target.label, url: target.url, status: result.status }
  })
)

const warnings = items.filter((item) => item.status !== 200)
const checkedAt = new Date().toISOString().slice(0, 10)

const source = `/**
 * Generated by scripts/site-check.mjs on ${checkedAt}.
 *
 * Do not edit by hand: the daily workflow rewrites this file after probing
 * every public destination linked from the portfolio.
 */
export const siteStatus = {
  checkedAt: '${checkedAt}',
  ok: ${warnings.length === 0},
  warnings: ${warnings.length},
  items: [
${items
  .map(
    (item) =>
      `    { label: '${item.label}', url: '${item.url}', status: ${item.status} },`
  )
  .join('\n')}
  ],
}
`

const previous = await fs.readFile(OUT, 'utf8').catch(() => '')

if (previous === source) {
  console.log('siteStatus.js already current')
} else {
  await fs.writeFile(OUT, source, 'utf8')
  console.log(
    warnings.length
      ? `siteStatus.js updated, ${warnings.length} link warning(s)`
      : 'siteStatus.js updated, all links OK'
  )
}
